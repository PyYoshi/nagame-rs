//! 設定で割り当て可能な操作と初期キー。Commandへの変換はViewerが行う。

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Shortcut {
    Open,
    OpenFolder,
    Previous,
    Next,
    Advance,
    First,
    Last,
    PreviousFolder,
    NextFolder,
    PreviousSibling,
    NextSibling,
    Parent,
    SkipPrevious,
    SkipNext,
    ZoomIn,
    ZoomOut,
    Fit,
    Actual,
    Rotate,
    Fullscreen,
    Slide,
    Manga,
    Settings,
    Info,
    Reload,
    SaveAs,
    CopyImage,
    CopyPath,
}
impl Shortcut {
    pub const ALL: &'static [Self] = &[
        Self::Open,
        Self::OpenFolder,
        Self::Previous,
        Self::Next,
        Self::Advance,
        Self::First,
        Self::Last,
        Self::PreviousFolder,
        Self::NextFolder,
        Self::PreviousSibling,
        Self::NextSibling,
        Self::Parent,
        Self::SkipPrevious,
        Self::SkipNext,
        Self::ZoomIn,
        Self::ZoomOut,
        Self::Fit,
        Self::Actual,
        Self::Rotate,
        Self::Fullscreen,
        Self::Slide,
        Self::Manga,
        Self::Settings,
        Self::Info,
        Self::Reload,
        Self::SaveAs,
        Self::CopyImage,
        Self::CopyPath,
    ];
    pub fn label(self) -> &'static str {
        match self {
            Self::Open => "画像を開く",
            Self::OpenFolder => "フォルダを開く",
            Self::Previous => "前の画像（漫画の読む方向に追従）",
            Self::Next => "次の画像（漫画の読む方向に追従）",
            Self::Advance => "次の画像（読む方向にかかわらず進む）",
            Self::First => "最初の画像",
            Self::Last => "最後の画像",
            Self::PreviousFolder => "前のフォルダ",
            Self::NextFolder => "次のフォルダ",
            Self::PreviousSibling => "前隣のフォルダ",
            Self::NextSibling => "次隣のフォルダ",
            Self::Parent => "親フォルダ",
            Self::SkipPrevious => "前へスキップ",
            Self::SkipNext => "次へスキップ",
            Self::ZoomIn => "ズームイン",
            Self::ZoomOut => "ズームアウト",
            Self::Fit => "ウィンドウに合わせる",
            Self::Actual => "原寸",
            Self::Rotate => "右回転",
            Self::Fullscreen => "全画面",
            Self::Slide => "自動スライド",
            Self::Manga => "漫画モード",
            Self::Settings => "設定",
            Self::Info => "画像の情報",
            Self::Reload => "再読み込み",
            Self::SaveAs => "名前を付けて保存",
            Self::CopyImage => "画像をコピー",
            Self::CopyPath => "パスをコピー",
        }
    }
}
pub fn defaults() -> BTreeMap<String, Shortcut> {
    use Shortcut::*;
    [
        ("ctrl-o", Open),
        ("cmd-o", Open),
        ("ctrl-shift-o", OpenFolder),
        ("left", Previous),
        ("right", Next),
        ("space", Advance),
        ("ctrl-home", First),
        ("ctrl-end", Last),
        ("up", PreviousFolder),
        ("down", NextFolder),
        ("ctrl-left", PreviousSibling),
        ("ctrl-right", NextSibling),
        ("alt-up", Parent),
        ("backspace", Parent),
        ("[", SkipPrevious),
        ("]", SkipNext),
        ("+", ZoomIn),
        ("=", ZoomIn),
        ("shift-+", ZoomIn),
        ("shift-=", ZoomIn),
        ("-", ZoomOut),
        ("0", Fit),
        ("f", Fit),
        ("1", Actual),
        ("r", Rotate),
        ("f11", Fullscreen),
        ("a", Slide),
        ("s", Slide),
        ("m", Manga),
        ("ctrl-,", Settings),
        ("cmd-,", Settings),
        ("i", Info),
        ("f5", Reload),
        ("ctrl-s", SaveAs),
        ("cmd-s", SaveAs),
        ("ctrl-c", CopyImage),
        ("cmd-c", CopyImage),
        ("ctrl-shift-c", CopyPath),
    ]
    .into_iter()
    .map(|(key, action)| (gpui::Keystroke::parse(key).unwrap().unparse(), action))
    .collect()
}
